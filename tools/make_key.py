"""Writes tmdb-key.js (not in git) from the TMDB_API_KEY environment variable or a .env file.

The web app reads window.TMDB_APP_KEY from it; the APK build copies it into the assets.
Run before testing or building:  python streamhub-store/tools/make_key.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STORE = os.path.normpath(os.path.join(HERE, ".."))
ENV = os.path.normpath(os.path.join(STORE, "..", ".env"))
OUT = os.path.join(STORE, "tmdb-key.js")


def read_key():
    try:
        with open(ENV, encoding="utf-8") as f:
            for line in f:
                if line.strip().startswith("TMDB_API_KEY="):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    except OSError:
        pass
    return ""


def main():
    key = read_key()
    if not key:
        print(json.dumps({"ok": False, "error": f"TMDB_API_KEY missing or empty in {ENV}"}))
        sys.exit(1)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/make_key.py from .env. Not in git.\n")
        f.write(f"window.TMDB_APP_KEY = {json.dumps(key)};\n")
    print(json.dumps({"ok": True, "file": OUT, "key_length": len(key)}))


if __name__ == "__main__":
    main()
